-- VIDEOKE: tabela e proteções para reservas
create table if not exists public.reservas (
  id bigint generated by default as identity primary key,
  nome_cliente text not null,
  data_evento date not null,
  local_evento text not null,
  status text not null default 'pendente'
    check (status in ('pendente', 'confirmada', 'cancelada')),
  valor_diaria numeric(10,2) not null default 300.00
    check (valor_diaria >= 0),
  created_at timestamptz not null default now()
);

-- Uma solicitação pendente ou confirmada segura a data para evitar conflito.
create unique index if not exists reservas_data_ativa_unique
on public.reservas (data_evento)
where status in ('pendente', 'confirmada');

create table if not exists public.videoke_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.reservas enable row level security;
alter table public.videoke_admins enable row level security;

-- A lista de administradores não é visível nem editável pelo navegador.
drop policy if exists "Admins can view admin list" on public.videoke_admins;
create policy "Admins can view admin list"
on public.videoke_admins for select
to authenticated
using (user_id = auth.uid());

-- Visitantes só podem consultar se uma data está ocupada, sem ler dados pessoais.
drop policy if exists "Public can check active dates" on public.reservas;
create policy "Public can check active dates"
on public.reservas for select
to anon, authenticated
using (status in ('pendente', 'confirmada'));

-- Visitantes podem criar solicitação pendente. Não podem confirmar reservas.
drop policy if exists "Public can request bookings" on public.reservas;
create policy "Public can request bookings"
on public.reservas for insert
to anon, authenticated
with check (
  status = 'pendente'
  and valor_diaria = 300
  and data_evento >= current_date
);

-- Somente o usuário listado em videoke_admins pode consultar dados pessoais,
-- confirmar ou cancelar reservas.
drop policy if exists "Only VIDEOKE admins manage bookings" on public.reservas;
create policy "Only VIDEOKE admins manage bookings"
on public.reservas for all
to authenticated
using (exists (
  select 1 from public.videoke_admins a where a.user_id = auth.uid()
))
with check (exists (
  select 1 from public.videoke_admins a where a.user_id = auth.uid()
));

